"""Expose the project skills to Claude Code.

The skills are written once, in `.agents/skills/<name>/SKILL.md`, which is where
Codex loads them from (`$<name>`). Claude Code only loads project skills from
`.claude/skills/`, so each skill gets a pointer file there: the same front
matter (name, description, flags) and a body that sends the reader to the real
file. That makes `/<name>` work in Claude Code without a second copy of the
instructions to keep in step.

    python scripts/sync_claude_skills.py           write the pointer files
    python scripts/sync_claude_skills.py --check   fail if they are out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".agents" / "skills"
TARGET = ROOT / ".claude" / "skills"
# Marks a file as written by this script; only such files are ever removed.
MARKER = "Generated by `scripts/sync_claude_skills.py`."


def front_matter(skill: Path) -> str:
    """The `---` block that opens a SKILL.md, fences included."""
    lines = skill.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise SystemExit(f"{skill.relative_to(ROOT).as_posix()}: no front matter")
    for end, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            return "\n".join(lines[: end + 1])
    raise SystemExit(f"{skill.relative_to(ROOT).as_posix()}: front matter is not closed")


def pointer(name: str, skill: Path) -> str:
    source = skill.relative_to(ROOT).as_posix()
    return (
        f"{front_matter(skill)}\n\n"
        f"# /{name}\n\n"
        f"Read `{source}` (path from the repository root) in full and follow it.\n"
        "That file is the skill; this one only makes it loadable in Claude Code.\n\n"
        f"{MARKER} Edit the file above, then run the script.\n"
    )


def expected() -> dict[str, str]:
    return {
        skill.parent.name: pointer(skill.parent.name, skill)
        for skill in sorted(SOURCE.glob("*/SKILL.md"))
    }


def stale(want: dict[str, str]) -> list[Path]:
    """Pointers this script wrote for skills that no longer exist.

    A directory is only stale when it holds nothing but a generated SKILL.md.
    Anything else in `.claude/skills/` (a skill written for Claude Code alone,
    or one with supporting files) is somebody's work and is left alone.
    """
    if not TARGET.is_dir():
        return []
    found = []
    for folder in sorted(p for p in TARGET.iterdir() if p.is_dir() and p.name not in want):
        files = list(folder.iterdir())
        if [f.name for f in files] == ["SKILL.md"] and MARKER in files[0].read_text(
            encoding="utf-8"
        ):
            found.append(folder)
    return found


def problems(want: dict[str, str]) -> list[str]:
    found = []
    for name, text in want.items():
        target = TARGET / name / "SKILL.md"
        if not target.is_file():
            found.append(f"missing: .claude/skills/{name}/SKILL.md")
        elif target.read_text(encoding="utf-8") != text:
            found.append(f"out of date: .claude/skills/{name}/SKILL.md")
    for folder in stale(want):
        found.append(f"no such skill in .agents/skills: .claude/skills/{folder.name}")
    return found


def main() -> int:
    want = expected()
    if "--check" in sys.argv[1:]:
        found = problems(want)
        for line in found:
            print(line)
        if found:
            print("Run: python scripts/sync_claude_skills.py")
        return 1 if found else 0
    for name, text in want.items():
        target = TARGET / name / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    for folder in stale(want):
        (folder / "SKILL.md").unlink()
        folder.rmdir()
    print(f"{len(want)} skills in .claude/skills")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
