"""Regenerate the Work ID and UAE ID release lists from the Passport List.

Only word/document.xml changes. The 15 render slots and signature rows stay
in the source table so the shared release-list renderer can trim empty slots.
Existing outputs are replaced only when their generated bytes differ.

Usage: python backend/scripts/build_id_release_list_templates.py
       (with the backend dependencies installed)
"""

from copy import copy, deepcopy
from io import BytesIO
from itertools import accumulate
from pathlib import Path
from zipfile import ZipFile

from lxml import etree

TEMPLATES = Path(__file__).resolve().parents[1] / "templates"
SOURCE = TEMPLATES / "GSSG-HR_300-004b_Passport_Release_List.docx"
DOCUMENT = "word/document.xml"
W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
PARA_ID = "{http://schemas.microsoft.com/office/word/2010/wordml}paraId"
HEADER_ROW = 6
FIRST_ITEM_ROW = 7
ITEM_SLOTS = 15
SIGNATURE_ROW = FIRST_ITEM_ROW + ITEM_SLOTS
DOCUMENT_COL = 3
# Logical order (rendered right to left): employee ID, name, nationality,
# Emirates ID number, expiry, received date, employee signature, handed over.
UAE_GRID = (1200, 2300, 1240, 2690, 1600, 1600, 1650, 1811)


def _replace_run(cell: etree._Element, old: str, new: str) -> None:
    (text,) = (node for node in cell.iter(W + "t") if node.text == old)
    text.text = new


def _placeholder(slot: int, key: str) -> str:
    return f"{{{{ item({slot}, '{key}') }}}}"


def _grid_count(parent: etree._Element, key: str, default: int) -> int:
    element = parent.find(W + key)
    return default if element is None else int(element.get(W + "val"))


def _add_expiry_column(table: etree._Element, rows: list[etree._Element]) -> None:
    grid = table.find(W + "tblGrid")
    if len(grid) != len(UAE_GRID) - 1 or sum(int(col.get(W + "w")) for col in grid) != sum(
        UAE_GRID
    ):
        raise ValueError("The passport table grid no longer matches the source layout")
    grid[DOCUMENT_COL].addnext(etree.Element(W + "gridCol"))
    for col, width in zip(grid, UAE_GRID, strict=True):
        col.set(W + "w", str(width))

    table_width = int(table.find(f"{W}tblPr/{W}tblW").get(W + "w"))
    grid_width = sum(UAE_GRID)
    # tcW uses the source's preferred table width, not the larger grid total.
    # Round the boundaries once so a spanning cell equals the sum it covers.
    boundaries = [
        round(twips * table_width / grid_width) for twips in accumulate(UAE_GRID, initial=0)
    ]
    used_ids = {p.get(PARA_ID) for p in table.iter(W + "p")}
    for index, row in enumerate(rows):
        first_col = _grid_count(row.find(W + "trPr"), "gridBefore", 0)
        end_offset = _grid_count(row.find(W + "trPr"), "gridAfter", 0)
        cells = row.findall(W + "tc")
        if HEADER_ROW <= index < SIGNATURE_ROW:
            number = cells[DOCUMENT_COL]
            expiry = deepcopy(number)
            para_id = f"{index:08X}"
            if para_id in used_ids:
                raise ValueError(f"Duplicate paragraph ID {para_id}")
            expiry.find(W + "p").set(PARA_ID, para_id)
            if index == HEADER_ROW:
                _replace_run(expiry, "رقم الهوية", "تاريخ انتهاء الهوية")
            else:
                slot = index - FIRST_ITEM_ROW
                _replace_run(
                    expiry, _placeholder(slot, "uae_id_no"), _placeholder(slot, "uae_id_expiry")
                )
            number.addnext(expiry)
        else:
            col = first_col
            for cell in cells:
                props = cell.find(W + "tcPr")
                span = _grid_count(props, "gridSpan", 1)
                if col <= DOCUMENT_COL < col + span:
                    span_node = props.find(W + "gridSpan")
                    if span_node is None:
                        span_node = etree.Element(W + "gridSpan")
                        props.find(W + "tcW").addnext(span_node)
                    span_node.set(W + "val", str(span + 1))
                    break
                col += span

        col = first_col
        for cell in row.findall(W + "tc"):
            props = cell.find(W + "tcPr")
            end = col + _grid_count(props, "gridSpan", 1)
            props.find(W + "tcW").set(W + "w", str(boundaries[end] - boundaries[col]))
            col = end
        if col + end_offset != len(UAE_GRID):
            raise ValueError(f"Invalid UAE ID grid spans in row {index}")


def _match_rtl_text(cell: etree._Element, reference: etree._Element) -> None:
    paragraph = cell.find(W + "p")
    source = reference.find(W + "p")
    props = paragraph.find(W + "pPr")
    props.find(W + "spacing").addprevious(deepcopy(source.find(f"{W}pPr/{W}bidi")))
    run = paragraph.find(W + "r")
    run.replace(run.find(W + "rPr"), deepcopy(source.find(f"{W}r/{W}rPr")))


def _build(source: ZipFile, *, uae: bool) -> None:
    original = source.read(DOCUMENT)
    document = etree.fromstring(original)
    table = document.find(f"{W}body/{W}tbl")
    rows = table.findall(W + "tr")
    cells = [row.findall(W + "tc") for row in rows]
    title = "الهوية الإماراتية" if uae else "بطاقة العمل"
    column = "رقم الهوية" if uae else "المسمى الوظيفي"
    handover = "الهوية" if uae else "البطاقة"
    received = "الهوية" if uae else "العمل"
    key = "uae_id_no" if uae else "position"

    # Preserve run formatting even where Word split an Arabic phrase.
    _replace_run(cells[5][0], " جواز السفر ", f" {title}")
    _replace_run(cells[HEADER_ROW][0], "ID", "الرقم الوظيفي")
    _match_rtl_text(cells[HEADER_ROW][0], cells[HEADER_ROW][1])
    _replace_run(cells[HEADER_ROW][DOCUMENT_COL], "رقم جواز السفر ", column)
    _replace_run(cells[HEADER_ROW][-1], "تاريخ تسليم الجواز", f"تاريخ تسليم {handover}")
    for slot in range(ITEM_SLOTS):
        row_cells = cells[FIRST_ITEM_ROW + slot]
        name = row_cells[1]
        item = row_cells[DOCUMENT_COL]
        _replace_run(item, _placeholder(slot, "passport_no"), _placeholder(slot, key))
        # Match the name cell before cloning the UAE expiry cell.
        for path in (f"{W}tcPr/{W}vAlign", f"{W}p/{W}pPr/{W}spacing"):
            property_node = item.find(path)
            property_node.getparent().replace(property_node, deepcopy(name.find(path)))
        if not uae:
            _match_rtl_text(item, name)
    _replace_run(cells[SIGNATURE_ROW][0], " جوازات ", " بطاقات ")
    _replace_run(cells[SIGNATURE_ROW][0], "السفر  أعلاه", f"{received} أعلاه")
    if uae:
        _add_expiry_column(table, rows)

    target = TEMPLATES / (
        "GSSG-HR_300-004d_UAE_ID_Release_List.docx"
        if uae
        else "GSSG-HR_300-004c_Work_ID_Release_List.docx"
    )
    declaration = original.partition(b"\n")[0]
    xml = declaration + b"\n" + etree.tostring(document, encoding="UTF-8")
    buffer = BytesIO()
    with ZipFile(buffer, "w") as output:
        output.comment = source.comment
        for member in source.infolist():
            output.writestr(
                copy(member), xml if member.filename == DOCUMENT else source.read(member)
            )
    payload = buffer.getvalue()
    if not target.exists() or target.read_bytes() != payload:
        target.write_bytes(payload)
        print(f"Generated {target.name}")


def main() -> None:
    with ZipFile(SOURCE) as source:
        _build(source, uae=False)
        _build(source, uae=True)


if __name__ == "__main__":
    main()
